"""retire_sequences — one-shot: nextval-fed <table>__rowid -> IDENTITY columns.

The live mnemosyne_* schemas were built by the shim-era path (serial defaults
+ sequences). The native contract (scripts/native_ddl.py + check_shape.py
strict mode) wants bigint GENERATED BY DEFAULT AS IDENTITY, plus GIN indexes
and FK CASCADEs that provision_schema asserts. This script converts the
column form in place (data preserved, idempotent), after which
provision_schema.py completes the rest of the shape.

Per table (schema-qualified, identifier-safe):
  1. if <t>__rowid default is nextval(...):  ALTER COLUMN ... DROP DEFAULT
     (the sequence may carry the column's OWNED flag; owned sequences are
     dropped by PG when the default dies — that is fine, IDENTITY makes its
     own).
  2. ALTER COLUMN ... ADD GENERATED BY DEFAULT AS IDENTITY
     (start = max(rowid)+1 so migrated/copied ids are never reused).
  "BY DEFAULT" (not ALWAYS) keeps OVERRIDING SYSTEM VALUE copy paths AND
  plain INSERTs working without OVERRIDING.

Usage: retire_sequences.py <schema> [<schema> ...] | --all
"""
from __future__ import annotations
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))

import os
import pathlib
import re
import sys

from mnemo_backends import psycopg_site as _ps
_ps.ensure_psycopg()
import psycopg

SKIP_TABLES = re.compile(r"_fts_(docsize|config|data|idx|content)$")


def dsn() -> str:
    d = os.environ.get("MNEMO_PG_DSN")
    if d:
        return d
    home = os.environ.get("HERMES_HOME") or os.path.expanduser("~/.hermes")
    p = pathlib.Path(home) / ".env"
    if p.is_file():
        for line in p.read_text().splitlines():
            if line.startswith("MNEMO_PG_DSN="):
                return line.split("=", 1)[1].strip()
    run = pathlib.Path.home() / "lcm-pg" / "run"
    if run.is_dir():
        return f"host={run} port=54329 dbname=lcm user=lcm01"
    raise SystemExit("no MNEMO_PG_DSN and no lcm-pg/run socket dir")


def convert(conn, schema: str) -> int:
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", schema):
        raise SystemExit(f"unsafe schema name: {schema}")
    changed = 0
    with conn as con, con.cursor() as cur:
        cur.execute(
            "SELECT c.relname, a.attname "
            "FROM pg_attribute a "
            "JOIN pg_class c ON c.oid = a.attrelid "
            "JOIN pg_namespace n ON n.oid = c.relnamespace "
            "LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum "
            "WHERE n.nspname = %s AND c.relkind = 'r' "
            "AND a.attname = c.relname || '__rowid' "
            "AND a.attidentity = '' AND a.attgenerated = '' "
            "AND pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval%%' "
            "ORDER BY c.relname",
            (schema,))
        rows = cur.fetchall()
        for table, col in rows:
            if SKIP_TABLES.search(table):
                continue
            mx = cur.execute(
                'SELECT COALESCE(max("%s"), 0) FROM "%s"."%s"' % (col, schema, table)
            ).fetchone()[0]
            cur.execute('ALTER TABLE "%s"."%s" ALTER COLUMN "%s" SET NOT NULL,'
                        'ALTER COLUMN "%s" DROP DEFAULT' % (schema, table, col, col))
            try:
                cur.execute(
                    'ALTER TABLE "%s"."%s" ALTER COLUMN "%s" '
                    "ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %d)"
                    % (schema, table, col, int(mx) + 1))
            except psycopg.Error as e:
                print(f"  {schema}.{table}: ADD IDENTITY failed: "
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
                raise
            print(f"  {schema}.{table}: serial -> IDENTITY (start {int(mx) + 1})")
            changed += 1
        if not rows:
            print(f"  {schema}: no nextval rowids left (already native)")
    return changed


def main() -> int:
    args = sys.argv[1:]
    if args == ["--all"]:
        with psycopg.connect(dsn(), autocommit=False) as con:
            schemas = [r[0] for r in con.execute(
                "SELECT nspname FROM pg_namespace WHERE nspname LIKE 'mnemosyne%' "
                "ORDER BY 1").fetchall()]
    else:
        schemas = args
    if not schemas:
        raise SystemExit(__doc__)
    total = 0
    for s in schemas:
        with psycopg.connect(dsn()) as con:
            total += convert(con, s)
    print(f"retire_sequences: converted {total} columns")
    return 0


if __name__ == "__main__":
    sys.exit(main())
