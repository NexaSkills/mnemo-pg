"""shape_pass: converge live mnemosyne_* schemas onto the native shape contract.
Adds identity rowids (BY DEFAULT), unique key indexes, FK CASCADE vec_*->base,
GIN tsvector indexes. Idempotent; reports per schema. No LLMs.

Key columns: working_memory/episodic_memory key on `id`, facts on `fact_id`
(live reality across all schemas; check_shape.py uses the same map).
"""
import sys, argparse
from pathlib import Path
_ROOT = Path(__file__).resolve().parents[1]
for _p in (_ROOT / "scripts", _ROOT / "mnemo_backends"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))
try:
    import psycopg_site  # noqa: F401
    psycopg_site.ensure_psycopg()
except Exception:
    pass
import psycopg

DEFAULTS = dict(host='/home/mybuddy/lcm-pg/run', port=54329, dbname='lcm', user='lcm01')
KEY_COL = {"working_memory": "id", "episodic_memory": "id", "facts": "fact_id"}
GIN = {"working_memory": "content_tsv", "episodic_memory": "content_tsv",
       "facts": "object_tsv"}
VEC = {"vec_working": "working_memory", "vec_episodes": "episodic_memory",
       "vec_facts": "facts"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("schemas", nargs="*")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    conn = psycopg.connect(**DEFAULTS, autocommit=True)
    cur = conn.cursor()
    if a.all or not a.schemas:
        schemas = [r[0] for r in cur.execute(
            "SELECT schema_name FROM information_schema.schemata "
            "WHERE schema_name LIKE 'mnemosyne%%' AND schema_name NOT LIKE 'mnemosyne_zz%%' "
            "ORDER BY 1")]
    else:
        schemas = a.schemas
    for s in schemas:
        q = s.replace('"', '""')
        present = {r[0] for r in cur.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema=%s", (s,))}
        done = []
        # 1. unique key indexes FIRST (FKs need them)
        for t, key in KEY_COL.items():
            if t not in present:
                continue
            try:
                cur.execute(f'CREATE UNIQUE INDEX IF NOT EXISTS uq_{t}_{key} '
                            f'ON "{q}"."{t}" ("{key}")')
                done.append(f"uq {t}")
            except psycopg.Error as e:
                print(f"  {s}: uq {t} skip: {str(e).splitlines()[0][:70]}")
        # 2. FK cascade vec_* -> base
        for v, base in VEC.items():
            if v not in present or base not in present:
                continue
            cur.execute(
                "SELECT con.conname, con.confdeltype FROM pg_constraint con "
                "JOIN pg_namespace n ON n.oid=con.connamespace "
                "WHERE n.nspname=%s AND con.conrelid=%s::regclass AND con.contype='f'",
                (s, f'"{q}"."{v}"'))
            fks = cur.fetchall()
            if any(d == "c" for _, d in fks):
                done.append(f"fk {v} ok")
                continue
            # find PK column of base
            cur.execute(
                "SELECT a.attname FROM pg_index i "
                "JOIN pg_class c ON c.oid=i.indrelid "
                "JOIN pg_namespace n ON n.oid=c.relnamespace "
                "JOIN unnest(i.indkey) WITH ORDINALITY k(k,o) ON true "
                "JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum=k.k "
                "WHERE n.nspname=%s AND c.relname=%s AND i.indisunique "
                "ORDER BY i.indnkeyatts, k.o LIMIT 1", (s, base))
            row = cur.fetchone()
            if not row:
                print(f"  {s}: fk {v} skip: no unique key found on {base}")
                continue
            pk = row[0]
            # Contract FK target is always the bigint <base>__rowid shim
            # column (vec.rowid stores that value; check_vec_coverage joins
            # on the same key). If absent, create it as identity from max.
            shim = f"{base}__rowid"
            cur.execute(
                "SELECT 1 FROM pg_class c JOIN pg_attribute a ON a.attrelid=c.oid "
                "JOIN pg_namespace n ON n.oid=c.relnamespace "
                "WHERE n.nspname=%s AND c.relname=%s AND a.attname=%s",
                (s, base, shim))
            if not cur.fetchone():
                try:
                    cur.execute(f'ALTER TABLE "{q}"."{base}" ADD COLUMN IF NOT EXISTS '
                                f'"{shim}" bigint')
                    cur.execute(f'SELECT COALESCE(max("{pk}"),0)::bigint+1 '
                                f'FROM "{q}"."{base}"')
                    nxt = cur.fetchone()[0]
                    cur.execute(f'ALTER TABLE "{q}"."{base}" ALTER COLUMN "{shim}" '
                                f'SET NOT NULL, ALTER COLUMN "{shim}" '
                                f'ADD GENERATED BY DEFAULT AS IDENTITY (START WITH {nxt})')
                    done.append(f"shim {base}")
                except psycopg.Error as e:
                    print(f"  {s}: fk {v} skip: shim {shim} create failed: "
                          f"{str(e).splitlines()[0][:70]}")
                    continue
            else:
                # ensure it's identity too
                cur.execute(
                    "SELECT a.attidentity FROM pg_class c JOIN pg_attribute a "
                    "ON a.attrelid=c.oid JOIN pg_namespace n ON n.oid=c.relnamespace "
                    "WHERE n.nspname=%s AND c.relname=%s AND a.attname=%s "
                    "AND a.attidentity<>''", (s, base, shim))
                if not cur.fetchone():
                    cur.execute(f'SELECT COALESCE(max("{shim}"),0)::bigint+1 '
                                f'FROM "{q}"."{base}"')
                    nxt = cur.fetchone()[0]
                    try:
                        cur.execute(f'ALTER TABLE "{q}"."{base}" '
                                    f'ALTER COLUMN "{shim}" DROP DEFAULT')
                    except psycopg.Error:
                        pass
                    try:
                        cur.execute(f'ALTER TABLE "{q}"."{base}" '
                                    f'ALTER COLUMN "{shim}" SET NOT NULL, '
                                    f'ALTER COLUMN "{shim}" '
                                    f'ADD GENERATED BY DEFAULT AS IDENTITY (START WITH {nxt})')
                        done.append(f"identity {base}.{shim}")
                    except psycopg.Error as e:
                        print(f"  {s}: identity {base}.{shim} skip: "
                              f"{str(e).splitlines()[0][:70]}")
            pk = shim
            # data validation: every vec rowid must exist in base
            cur.execute(f'''SELECT count(*) FROM "{q}"."{v}" v
                WHERE v.rowid IS NOT NULL AND NOT EXISTS
                (SELECT 1 FROM "{q}"."{base}" b WHERE b."{pk}" = v.rowid)''')
            orphans = cur.fetchone()[0]
            if orphans:
                print(f"  {s}: fk {v} skip: {orphans} orphan rows in {v}")
                continue
            for cn, _ in fks:
                try:
                    cur.execute(f'ALTER TABLE "{q}"."{v}" DROP CONSTRAINT "{cn}"')
                except psycopg.Error:
                    pass
            try:
                cur.execute(
                    f'ALTER TABLE "{q}"."{v}" ADD CONSTRAINT "{v}_base_fk" '
                    f'FOREIGN KEY (rowid) REFERENCES "{q}"."{base}" ("{pk}") '
                    'ON DELETE CASCADE')
                done.append(f"fk {v} (->{base}.{pk})")
            except psycopg.Error as e:
                print(f"  {s}: fk {v} skip: {str(e).splitlines()[0][:90]}")
        # 3. identity rowid (BY DEFAULT) — after FKs so table locks are ordered
        cur.execute(
            "SELECT c.relname, a.attname, COALESCE(a.attidentity,''), "
            "COALESCE(pg_get_expr(d.adbin,d.adrelid),'') "
            "FROM pg_class c JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum>0 "
            "LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum "
            "JOIN pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname=%s AND a.attname = c.relname || '__rowid'", (s,))
        for t, col, ident, dflt in cur.fetchall():
            if ident == "d":
                continue
            cur.execute(f'SELECT COALESCE(max("{col}"),0)::bigint+1 FROM "{q}"."{t}"')
            nxt = cur.fetchone()[0]
            try:
                if dflt:
                    cur.execute(f'ALTER TABLE "{q}"."{t}" ALTER COLUMN "{col}" DROP DEFAULT')
                cur.execute(f'ALTER TABLE "{q}"."{t}" ALTER COLUMN "{col}" SET NOT NULL')
                cur.execute(f'ALTER TABLE "{q}"."{t}" ALTER COLUMN "{col}" '
                            f'ADD GENERATED BY DEFAULT AS IDENTITY (START WITH {nxt})')
                done.append(f"id {t}")
            except psycopg.Error as e:
                print(f"  {s}: id {t} skip: {str(e).splitlines()[0][:70]}")
        # 4. GIN
        for t, c in GIN.items():
            if t not in present:
                continue
            try:
                cur.execute(f'CREATE INDEX IF NOT EXISTS gin_{t}_{c} '
                            f'ON "{q}"."{t}" USING gin ("{c}")')
                done.append(f"gin {t}")
            except psycopg.Error as e:
                print(f"  {s}: gin {t} skip: {str(e).splitlines()[0][:70]}")
        print(f"{s}: {'; '.join(done) if done else 'no changes'}")
    conn.close()
    print("SHAPE PASS done")


if __name__ == "__main__":
    main()
